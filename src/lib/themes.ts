export function getTheme(gender: Gender, ageGroup: AgeGroup): ThemeConfig {
  const key: ThemeKey = `${gender}_${ageGroup}`;
  return themes[key];
}

export function getAgeGroup(age: number): AgeGroup {
  if (age <= 30) return 'young';
  if (age <= 45) return 'middle';
  return 'mature';
}
